/**
 * Real Local Lorem Ipsum Generator
 */
export function generateLoremIpsum(paragraphs: number = 3): ProcessingResult {
  try {
    const loremBase = [
      "Lorem ipsum dolor sit amet, consectetur adipiscing elit. Sed do eiusmod tempor incididunt ut labore et dolore magna aliqua.",
      "Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris nisi ut aliquip ex ea commodo consequat.",
      "Duis aute irure dolor in reprehenderit in voluptate velit esse cillum dolore eu fugiat nulla pariatur.",
      "Excepteur sint occaecat cupidatat non proident, sunt in culpa qui officia deserunt mollit anim id est laborum."
    ];

    const resultParagraphs = [];
    for (let i = 0; i < paragraphs; i++) {
      resultParagraphs.push(loremBase[i % loremBase.length]);
    }

    const text = resultParagraphs.join('\n\n');
    const blob = new Blob([text], { type: 'text/plain' });

    return {
      success: true,
      outputBlob: blob,
      outputUrl: URL.createObjectURL(blob),
      outputFileName: 'lorem_ipsum.txt',
      data: text,
      outputSize: blob.size
    };
  } catch (err: any) {
    return {
      success: false,
      error: `Lorem generator error: ${err.message}`
    };
  }
}

/**
 * Real Local Favicon Package Generator
 */
export async function generateFaviconPackage(file?: File): Promise<ProcessingResult> {
  try {
    const canvas = document.createElement('canvas');
    canvas.width = 32;
    canvas.height = 32;
    const ctx = canvas.getContext('2d');

    if (ctx) {
      if (file) {
        const bitmap = await createImageBitmap(file);
        ctx.drawImage(bitmap, 0, 0, 32, 32);
      } else {
        ctx.fillStyle = '#0F172A';
        ctx.fillRect(0, 0, 32, 32);
        ctx.fillStyle = '#7C3AED';
        ctx.fillRect(8, 8, 16, 16);
      }
    }

    const blob = await new Promise<Blob>((res) => canvas.toBlob(b => res(b!), 'image/x-icon'));
    const outputUrl = URL.createObjectURL(blob);

    return {
      success: true,
      outputBlob: blob,
      outputUrl,
      outputFileName: 'favicon.ico',
      outputSize: blob.size,
      data: 'Generated standard 32x32 Favicon icon.'
    };
  } catch (err: any) {
    return {
      success: false,
      error: `Favicon generator error: ${err.message}`
    };
  }
}
