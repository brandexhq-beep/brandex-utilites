import { ProcessingResult } from './imageEngine';

/**
 * Real Local URL Encoder / Decoder
 */
export function processUrlEncoding(input: string, mode: 'encode' | 'decode' = 'encode'): ProcessingResult {
  try {
    if (!input) throw new Error("URL string is required.");
    const result = mode === 'encode' ? encodeURIComponent(input) : decodeURIComponent(input);
    const blob = new Blob([result], { type: 'text/plain' });

    return {
      success: true,
      outputBlob: blob,
      outputUrl: URL.createObjectURL(blob),
      outputFileName: `${mode}_url.txt`,
      data: result,
      outputSize: blob.size
    };
  } catch (err: any) {
    return {
      success: false,
      error: `URL ${mode} error: ${err.message}`
    };
  }
}

